#!/usr/bin/env bash
# Regenerates test/utils/AdminSurface.sol: every state-changing (nonpayable/payable) function of every
# contract the template deploys, taken from the compiled ABIs. test/PrivilegeIsolation.t.sol attacks
# each one through every session route. Re-run after changing dependencies.
set -euo pipefail
cd "$(dirname "$0")/.."
forge build --quiet

CONTRACTS="Safe Safe7579 SmartSession EntryPoint OwnableValidator TimeFramePolicy SimpleGasPolicy GasFeeCapPolicy FunctionWhitelistPolicy AddressWhitelistPolicy SpendingLimitPolicy MockERC20"
TMP=$(mktemp -d)
for c in $CONTRACTS; do
  forge inspect "$c" abi --json >"$TMP/$c.abi.json"
  forge inspect "$c" methodIdentifiers --json >"$TMP/$c.ids.json"
done

python3 -I - "$TMP" $CONTRACTS >test/utils/AdminSurface.sol <<'PY'
import json, sys
tmp, contracts = sys.argv[1], sys.argv[2:]

def canon(t):
    if t["type"].startswith("tuple"):
        return "(" + ",".join(canon(c) for c in t["components"]) + ")" + t["type"][len("tuple"):]
    return t["type"]

print("// SPDX-License-Identifier: MIT")
print("// GENERATED by script/gen-admin-surface.sh from the compiled ABIs - do not edit by hand.")
print("pragma solidity ^0.8.28;\n")
print("library AdminSurface {")
for c in contracts:
    abi = json.load(open(f"{tmp}/{c}.abi.json"))
    ids = json.load(open(f"{tmp}/{c}.ids.json"))
    fns = sorted({f["name"] + "(" + ",".join(canon(i) for i in f["inputs"]) + ")"
                  for f in abi if f["type"] == "function" and f["stateMutability"] in ("nonpayable", "payable")})
    print(f"    function {c}() internal pure returns (bytes4[] memory s, string[] memory n) {{")
    print(f"        s = new bytes4[]({len(fns)});")
    print(f"        n = new string[]({len(fns)});")
    for i, sig in enumerate(fns):
        print(f"        s[{i}] = 0x{ids[sig]};")
        print(f"        n[{i}] = \"{c}.{sig.split('(')[0]}\";")
    print("    }\n")
print("}")
PY
rm -rf "$TMP"
forge fmt test/utils/AdminSurface.sol
echo "wrote test/utils/AdminSurface.sol"
